package com.streamlinemyjob.inspect.tools.trimmer

/**
 * Writes `trimmer/TrimmerTestData.bas` (designs/stage-B-trimmer.md 4.10.3) from the cases: VBA module
 * `TrimmerTestData`, plain ASCII, CRLF line ends, no procedure of 400 lines or more (4.9).
 */
internal object BasWriter {
    /** Statements per generated part, so each `Sub`/`Function` stays well under 400 lines. */
    const val PART_LINES = 300

    /** A listing line is written in pieces of at most this many characters (4.10.3). */
    const val PIECE = 200

    fun write(cases: List<TestSetGenerator.TestCase>, seed: Long): String {
        val b = Bas()
        b += "Attribute VB_Name = \"TrimmerTestData\""
        b += "' GENERATED by `tools trimmer-testset` (seed $seed) from the Kotlin reference model"
        b += "' (tools/src/main/kotlin/com/streamlinemyjob/inspect/tools/trimmer/TestSetGenerator.kt)."
        b += "' Never edit by hand: regenerate (designs/stage-B-trimmer.md 4.10.3). Made-up data only."
        b += "'"
        b += "' CaseCount, CaseName(i), CaseExpected(i), FillCase(i, ws). The cases are numbered from 1."
        b += "' CaseExpected is the expected listing (4.10.2, ends with a ROWS line) or the expected message."
        b += "' The last case, canary, has a listing made wrong on purpose (two regs swapped): it must fail."
        b += "' Case big is made here by BigNext (a seeded generator); its CaseExpected is one line"
        b += "' BLOCK <name> <vehicle rows> per block of the result, then ROWS <n>. Each of its rows has"
        b += "' Veh Description = \"Car \" & <Reg Number as typed> & \" m\" & <Mileage> & \" p\" & <Selling Price in pence>,"
        b += "' so a row whose cells were split up can be found."
        b += "' Case taken-name: FillCase also adds tabs Trimmed and Trimmed (2) after the export sheet,"
        b += "' each with one cell, A1, that must still be there after the trim."
        b += "Option Explicit"
        b += ""
        val big = cases.single { it.bigSeed != null }
        b += "Private Const BIG_SEED As Long = ${big.bigSeed}"
        b += "Private Const BIG_ROWS As Long = ${TestSetGenerator.BIG_ROWS}"
        b += ""

        b += "Public Function CaseCount() As Long"
        b += "    CaseCount = ${cases.size}"
        b += "End Function"
        b += ""
        b += "Public Function CaseName(ByVal i As Long) As String"
        b += "    Select Case i"
        cases.forEachIndexed { k, c -> b += "        Case ${k + 1}: CaseName = ${lit(c.name)}" }
        b += "        Case Else: CaseName = \"\""
        b += "    End Select"
        b += "End Function"
        b += ""
        b += "Public Function CaseExpected(ByVal i As Long) As String"
        b += "    Select Case i"
        cases.forEachIndexed { k, _ -> b += "        Case ${k + 1}: CaseExpected = Expected_${k + 1}()" }
        b += "        Case Else: CaseExpected = \"\""
        b += "    End Select"
        b += "End Function"
        b += ""
        b += "Public Sub FillCase(ByVal i As Long, ByVal ws As Worksheet)"
        b += "    Select Case i"
        cases.forEachIndexed { k, _ -> b += "        Case ${k + 1}: Case_${k + 1} ws" }
        b += "    End Select"
        b += "End Sub"

        cases.forEachIndexed { k, c ->
            val n = k + 1
            b += ""
            b += "' ---- case $n: ${c.name} ----"
            if (c.bigSeed != null) writeBigFill(b, n) else writeFill(b, n, c)
            writeExpected(b, n, c.expected)
        }
        if (cases.any { it.oldTabs.isNotEmpty() }) writeAddOldTab(b)
        writeBigHelpers(b)
        return b.text()
    }

    private fun writeFill(b: Bas, n: Int, c: TestSetGenerator.TestCase) {
        val body = mutableListOf<String>()
        c.sheet.rows.forEachIndexed { r, row ->
            row.forEachIndexed { col, cell ->
                val at = "ws.Cells(${r + 1}, ${col + 1})"
                when (cell) {
                    Cell.Empty -> {}
                    is Cell.Text -> {
                        require(cell.text.isNotEmpty()) { "an empty text cell is written as Cell.Empty" }
                        if (cell.numberFormat != Cell.GENERAL) body += "$at.NumberFormat = ${lit(cell.numberFormat)}"
                        body += "$at.Value = ${lit(cell.text)}"
                    }
                    is Cell.Number -> {
                        if (cell.numberFormat != Cell.GENERAL) body += "$at.NumberFormat = ${lit(cell.numberFormat)}"
                        body += "$at.Value = ${TrimRules.shortest(cell.value)}"
                    }
                }
            }
        }
        val parts = body.chunked(PART_LINES)
        b += "Private Sub Case_$n(ws As Worksheet)"
        if (parts.size == 1) {
            parts[0].forEach { b += "    $it" }
        } else {
            parts.indices.forEach { p -> b += "    Case_${n}_part${p + 1} ws" }
        }
        for (t in c.oldTabs) b += "    AddOldTab ws.Parent, ${lit(t)}"
        b += "End Sub"
        if (parts.size > 1) {
            parts.forEachIndexed { p, lines ->
                b += ""
                b += "Private Sub Case_${n}_part${p + 1}(ws As Worksheet)"
                lines.forEach { b += "    $it" }
                b += "End Sub"
            }
        }
    }

    private fun writeExpected(b: Bas, n: Int, expected: String) {
        val body = mutableListOf<String>()
        // Lines of the listing, each ending in vbLf; the last piece of a message (no newline) has none.
        val lines = expected.split('\n')
        lines.forEachIndexed { i, line ->
            val endsLine = i < lines.lastIndex
            if (!endsLine && line.isEmpty()) return@forEachIndexed
            val pieces = if (line.isEmpty()) listOf("") else line.chunked(PIECE)
            pieces.forEachIndexed { p, piece ->
                val nl = endsLine && p == pieces.lastIndex
                body += "s = s & ${lit(piece)}" + if (nl) " & vbLf" else ""
            }
        }
        val parts = body.chunked(PART_LINES)
        b += ""
        b += "Private Function Expected_$n() As String"
        if (parts.size == 1) {
            b += "    Dim s As String"
            parts[0].forEach { b += "    $it" }
            b += "    Expected_$n = s"
        } else {
            b += "    Expected_$n = " + parts.indices.joinToString(" & ") { "Expected_${n}_part${it + 1}()" }
        }
        b += "End Function"
        if (parts.size > 1) {
            parts.forEachIndexed { p, ls ->
                b += ""
                b += "Private Function Expected_${n}_part${p + 1}() As String"
                b += "    Dim s As String"
                ls.forEach { b += "    $it" }
                b += "    Expected_${n}_part${p + 1} = s"
                b += "End Function"
            }
        }
    }

    private fun writeBigFill(b: Bas, n: Int) {
        b += "Private Sub Case_$n(ws As Worksheet)"
        b += "    Dim s As Long, r As Long, disp As String, reg As String, mileage As Long, pennies As Long"
        TrimRules.KEPT.forEachIndexed { c, h -> b += "    ws.Cells(1, ${c + 1}).Value = ${lit(h)}" }
        b += "    s = BIG_SEED"
        b += "    For r = 2 To BIG_ROWS + 1"
        b += "        disp = BigDisposal(BigNext(s) Mod ${TestSetGenerator.BIG_DISPOSALS.size})"
        b += "        reg = BigReg(s)"
        b += "        mileage = BigNext(s) Mod 120001"
        b += "        If BigNext(s) Mod 5 = 0 Then"
        b += "            pennies = 0"
        b += "        Else"
        b += "            pennies = 500000 + BigNext(s) Mod 4000001"
        b += "        End If"
        b += "        ws.Cells(r, 1).Value = \"Car \" & reg & \" m\" & mileage & \" p\" & pennies"
        b += "        If Len(reg) > 0 Then ws.Cells(r, 2).Value = reg"
        b += "        ws.Cells(r, 3).Value = mileage"
        b += "        ws.Cells(r, 4).NumberFormat = ${lit(TestSetGenerator.PRICE_FORMAT)}"
        b += "        ws.Cells(r, 4).Value = pennies / 100"
        b += "        ws.Cells(r, 5).Value = disp"
        b += "    Next r"
        b += "End Sub"
    }

    private fun writeAddOldTab(b: Bas) {
        b += ""
        b += "' Adds a tab named tabName after the last sheet; found by its name not being there before (as 4.2 step 4)."
        b += "Private Sub AddOldTab(ByVal wb As Workbook, ByVal tabName As String)"
        b += "    Dim before As String, sh As Worksheet, found As Worksheet, n As Long, count As Long"
        b += "    before = \"|\""
        b += "    For Each sh In wb.Worksheets"
        b += "        before = before & sh.Name & \"|\""
        b += "    Next sh"
        b += "    count = wb.Worksheets.Count"
        b += "    wb.Worksheets.Add After:=wb.Worksheets(wb.Worksheets.Count)"
        b += "    For Each sh In wb.Worksheets"
        b += "        If InStr(1, before, \"|\" & sh.Name & \"|\", vbBinaryCompare) = 0 Then"
        b += "            Set found = sh"
        b += "            n = n + 1"
        b += "        End If"
        b += "    Next sh"
        b += "    If n <> 1 Or wb.Worksheets.Count <> count + 1 Then Err.Raise vbObjectError + 513, , \"could not add the tab \" & tabName"
        b += "    found.Name = tabName"
        b += "    found.Cells(1, 1).Value = \"Old tab \" & tabName & \", left as it is\""
        b += "End Sub"
    }

    private fun writeBigHelpers(b: Bas) {
        b += ""
        b += "' The minimal standard generator (Park and Miller) by Schrage's method: every value fits a Long."
        b += "Private Function BigNext(ByRef s As Long) As Long"
        b += "    Dim hi As Long, lo As Long, t As Long"
        b += "    hi = s \\ 127773"
        b += "    lo = s Mod 127773"
        b += "    t = 16807 * lo - 2836 * hi"
        b += "    If t <= 0 Then t = t + 2147483647"
        b += "    s = t"
        b += "    BigNext = t"
        b += "End Function"
        b += ""
        b += "Private Function BigDisposal(ByVal k As Long) As String"
        b += "    Select Case k"
        TestSetGenerator.BIG_DISPOSALS.forEachIndexed { i, d -> b += "        Case $i: BigDisposal = ${lit(d)}" }
        b += "    End Select"
        b += "End Function"
        b += ""
        b += "' A reg from a pattern: L a capital letter, l a small letter, d a digit, anything else as is."
        b += "Private Function BigReg(ByRef s As Long) As String"
        b += "    Dim pat As String, out As String, i As Long, ch As String"
        b += "    Select Case BigNext(s) Mod 10"
        TestSetGenerator.BIG_PATTERNS.forEachIndexed { i, p -> b += "        Case $i: pat = ${lit(p)}" }
        b += "    End Select"
        b += "    For i = 1 To Len(pat)"
        b += "        ch = Mid$(pat, i, 1)"
        b += "        If ch = \"L\" Then"
        b += "            out = out & Chr$(65 + BigNext(s) Mod 26)"
        b += "        ElseIf ch = \"l\" Then"
        b += "            out = out & Chr$(97 + BigNext(s) Mod 26)"
        b += "        ElseIf ch = \"d\" Then"
        b += "            out = out & Chr$(48 + BigNext(s) Mod 10)"
        b += "        Else"
        b += "            out = out & ch"
        b += "        End If"
        b += "    Next i"
        b += "    BigReg = out"
        b += "End Function"
    }

    /** A VBA string literal: double quotes doubled; ASCII only. */
    fun lit(s: String): String {
        require(s.all { it.code in 32..126 }) { "not plain ASCII: $s" }
        return "\"" + s.replace("\"", "\"\"") + "\""
    }

    private class Bas {
        private val lines = mutableListOf<String>()
        operator fun plusAssign(line: String) { lines += line }
        fun text(): String = lines.joinToString("") { "$it\r\n" }
    }
}
